import pandas as pd
import matplotlib.pyplot as plt
from google.colab import files

# Subir archivos
uploaded = files.upload()

# Leer y graficar cada archivo
plt.figure(figsize=(12, 6))

for filename in uploaded.keys():
    df = pd.read_csv(filename, sep="\t", comment='#', header=None)
    df.dropna(inplace=True)
    df.columns = ['X', 'Y']
    plt.plot(df['X'], df['Y'], label=filename.replace(".asc", ""))

plt.xlabel("X")
plt.ylabel("Y")
plt.title("Gráfica de Muestras")
plt.legend()
plt.grid(True)
plt.tight_layout()
plt.show()
